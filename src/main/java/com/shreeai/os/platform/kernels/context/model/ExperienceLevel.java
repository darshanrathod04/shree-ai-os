package com.shreeai.os.platform.kernels.context.model;

/**
 * <b>ExperienceLevel</b>
 *
 * <p>Defines the user's experience level for content personalization.</p>
 *
 * <p><b>Ownership:</b> Context Kernel</p>
 * <p><b>Version:</b> 1.0</p>
 */
public enum ExperienceLevel {
    /**
     * Beginner level - new to the subject.
     */
    BEGINNER,

    /**
     * Intermediate level - some experience.
     */
    INTERMEDIATE,

    /**
     * Advanced level - significant experience.
     */
    ADVANCED,

    /**
     * Expert level - mastery of the subject.
     */
    EXPERT
}